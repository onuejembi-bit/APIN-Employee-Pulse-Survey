/**
 * Returns the exact count of questions for a section, including individual statements in Likert matrices.
 */
export function getSectionQuestionCount(section: SurveySection): number {
  return section.questions.reduce((sum, q) => {
    if (q.type === 'likert-matrix' && q.likertStatements) {
      return sum + q.likertStatements.length;
    }
    return sum + 1;
  }, 0);
}

/**
 * Returns the total count of questions in the entire survey (54 questions).
 */
export function getTotalSurveyQuestionCount(): number {
  return SURVEY_SECTIONS.reduce((sum, sec) => sum + getSectionQuestionCount(sec), 0);
}
